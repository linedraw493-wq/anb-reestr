"""Код не письмом, а голосом: робот звонит и диктует цифры.

Слово владельца 07.09.2026: «сделай вместо SMS звонки с оператора
какого-нибудь».

**Почему это лучше SMS в нашем случае.** У SMS через общую подпись
провайдера не работает Beeline — а это четыре кода оператора из
одиннадцати, треть базы. Звонок идёт по обычной телефонной сети и доходит
до всех операторов одинаково. И стоит он дешевле: 4–10 ₸ за проверку
против 16,60 ₸ за SMS.

**Провайдер — AutoCall.kz.** Выбран потому, что работает по Казахстану, не
требует документов и договора на старте, а код диктует синтезом речи — свои
аудиофайлы записывать не надо. У Mobizon, которым мы шлём SMS, голосовых
кодов нет вовсе (проверено по их документации 07.09.2026).

**Что нужно от владельца:** завести кабинет на autocall.kz, положить денег
и взять токен (Настройки → API интеграция). Дальше он кладётся в переменную
окружения `AUTOCALL_API_KEY` (в коде она зовётся `nastroyki.AUTOCALL_KLYUCH`),
и звонки включаются сами — код уже написан и выкачен.
Пока ключа нет, всё работает как раньше: SMS, а без неё телеграм-чат.

Устройство разговора: робот произносит код по одной цифре и повторяет его
второй раз. Цифры вразбивку — иначе синтез читает «3075» как «три тысячи
семьдесят пять», и человек не понимает, что набирать.
"""

import logging

import httpx

from . import nastroyki

log = logging.getLogger("reestr.zvonok")

# Что произносит робот. Название Ассоциации в начале — чтобы человек понял,
# кто звонит, и не бросил трубку.
SHABLON = "Ассоциация блогеров. Код подтверждения: {cifry}. Повторяю: {cifry}."


def vklyucheno() -> bool:
    return bool(nastroyki.AUTOCALL_KLYUCH)


def _po_cifram(kod: str) -> str:
    """«3075» → «3, 0, 7, 5». Слитно синтез читает это числом."""
    return ", ".join(kod)


async def pozvonit_kod(kod: str, telefon: str) -> bool:
    """Позвонить и продиктовать код. True — провайдер принял вызов в работу.

    Как и у SMS, «принял» не равно «человек услышал»: трубку могут не
    взять. Но если провайдер отказал сразу, врать про доставку нельзя —
    отвечаем False, и экран честно говорит, что не дозвонились.
    """
    if not vklyucheno():
        return False

    telo = {
        "name": "Код входа в реестр",
        "type": "regular",
        "audio_id": [
            {"type": "synthesis", "data": {"text": SHABLON.format(cifry=_po_cifram(kod))}}
        ],
        "list_id": [{"number": telefon}],
    }
    try:
        async with httpx.AsyncClient(timeout=20) as klient:
            otvet = await klient.post(
                f"{nastroyki.AUTOCALL_ADRES.rstrip('/')}/api/v1/autocalls",
                json=telo,
                headers={"Authorization": f"Bearer {nastroyki.AUTOCALL_KLYUCH}"},
            )
    except httpx.HTTPError as beda:
        # Сеть легла — это не повод ронять вход. Скажем «не смогли».
        log.warning("звонок не ушёл, сеть: %s", beda)
        return False

    if otvet.status_code >= 400:
        log.warning("звонок не принят провайдером: %s %s", otvet.status_code, otvet.text[:200])
        return False

    log.info("звонок с кодом принят провайдером")
    return True
