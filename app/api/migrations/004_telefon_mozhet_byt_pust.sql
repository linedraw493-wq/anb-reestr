-- В таблице заказчика телефон есть только у 34 человек из 417. А телефон у нас
-- личность — значит, остальных 383 просто нельзя было бы завести.
--
-- Решение: заготовку можно завести без телефона. Человек вписывает свой номер
-- сам, когда впервые открывает личную ссылку — экран приглашения это уже умеет
-- («Изменить»). После первого входа телефон появляется и дальше работает как
-- обычно.
--
-- Уникальность сохраняется: Postgres разрешает много пустых значений, но два
-- одинаковых номера — нет.

alter table lyudi alter column telefon drop not null;

-- Чтобы заготовку было видно в админке до того, как человек дошёл.
alter table lyudi add column if not exists otkuda text;

comment on column lyudi.telefon is
  'Пусто — заготовка из таблицы заказчика, номер человек впишет сам при входе';
