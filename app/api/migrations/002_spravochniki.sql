  ('Астана', 'Нура'), ('Астана', 'Сарыаркинский'),
  ('Шымкент', 'Абайский'), ('Шымкент', 'Аль-Фарабийский'),
  ('Шымкент', 'Енбекшинский'), ('Шымкент', 'Каратауский'), ('Шымкент', 'Туран')
) as r(gorod, nazvanie) on r.gorod = g.nazvanie
on conflict (gorod_id, nazvanie) do nothing;
