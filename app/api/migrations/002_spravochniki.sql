from goroda g
join (values
  ('Алматы', 'Алатауский'), ('Алматы', 'Алмалинский'), ('Алматы', 'Ауэзовский'),
  ('Алматы', 'Бостандыкский'), ('Алматы', 'Жетысуский'), ('Алматы', 'Медеуский'),
  ('Алматы', 'Наурызбайский'), ('Алматы', 'Турксибский'),
