-- --------------------------------------------------- приглашение: открыли или нет
-- Чтобы заказчик видел «разослал 305, открыли 120, дошли 47» и знал,
-- кому напомнить, а не рассылал вслепую.

alter table priglasheniya add column if not exists otkryto_v timestamptz;

comment on column priglasheniya.otkryto_v is 'Когда ссылку открыли впервые. Пусто — не открывали.';

-- ------------------------------------------------------------------ уведомления
-- Решение раунда 2: уведомление живёт внутри сайта, видно при заходе.
-- chat_telegram — на будущее: если человек сам напишет боту, сможем слать туда.

create table uvedomleniya (
  id            bigserial primary key,
  chelovek_id   bigint not null references lyudi(id) on delete cascade,
  tekst         text not null,
  kuda          text,                          -- куда ведёт по нажатию
  prochitano_v  timestamptz,
  sozdano_v     timestamptz not null default now()
);

create index uvedomleniya_komu_idx
  on uvedomleniya (chelovek_id, sozdano_v desc)
  where prochitano_v is null;

alter table lyudi add column if not exists chat_telegram text;

comment on column lyudi.chat_telegram is
  'Куда слать уведомления в Telegram. Заполняется, только если человек сам открыл бота — бот не умеет писать первым.';
