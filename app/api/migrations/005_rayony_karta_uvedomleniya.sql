-- ------------------------------------------------------- районы, которых не было
-- Официальные районы есть не у всех городов Казахстана — только у шести.
-- Где их нет, адрес это сам город, и это правильно, а не пропуск.

insert into rayony (gorod_id, nazvanie)
select g.id, r.nazvanie
from goroda g
join (values
  -- Караганда: два района
  ('Караганда', 'Алихана Бокейханова'), ('Караганда', 'Казыбекбийский'),
  -- Актобе: два района
  ('Актобе', 'Астана'), ('Актобе', 'Алматы'),
  -- Тараз: два района
  ('Тараз', 'Аулие-Атинский'), ('Тараз', 'Жибек Жолы')
) as r(gorod, nazvanie) on r.gorod = g.nazvanie
on conflict (gorod_id, nazvanie) do nothing;

-- ------------------------------------------------------------ координаты под карту
-- Точка ставится на город (а у больших городов — на район), не на дом.
-- Домашних адресов мы не собираем и на карте не показываем.

alter table goroda add column if not exists shirota  numeric(9,6);
alter table goroda add column if not exists dolgota  numeric(9,6);

update goroda set shirota = t.sh, dolgota = t.dl
from (values
