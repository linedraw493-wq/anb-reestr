-- Спека, день 4: «числа ложатся в поля карточки с пометкой источника
-- **и датой**». Пометка была с самого начала («со скрина» / «со слов»),
-- а даты не было: рекламодатель видел цифру и не знал, она вчерашняя или
-- трёхмесячной давности. Сверка 07.09.2026 это и поймала.
--
-- Ставится всякий раз, когда цифры записываются: блогером, модератором или
-- одобрением правки. У старых карточек пусто — врать задним числом нельзя,
-- экран в этом случае просто не показывает дату.

alter table kartochki add column if not exists cifry_ot timestamptz;

comment on column kartochki.cifry_ot is
  'Когда подписчики и охват записаны в последний раз. Пусто — до 07.09.2026.';
